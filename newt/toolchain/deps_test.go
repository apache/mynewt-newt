// newTestCompiler creates a compiler which is usable for tests that do not
// need a loaded compiler package.
func newTestCompiler() *Compiler {
	c := &Compiler{
		mutex:           &sync.Mutex{},
		objPathList:     map[string]bool{},
		extraDeps:       []string{},
		compileCommands: []CompileCommand{},
	}
	c.depTracker = NewDepTracker(c)

	return c
}

// Run with -race to detect unsynchronized access.
func TestCompilerConcurrentUpdates(t *testing.T) {
	c := newTestCompiler()
	dir := t.TempDir()

	const n = 50
	var wg sync.WaitGroup
	for i := 0; i < n; i++ {
		obj := filepath.Join(dir, fmt.Sprintf("f%d.o", i))
		if err := os.WriteFile(obj, nil, 0644); err != nil {
			t.Fatal(err)
		}

		wg.Add(3)
		go func() {
			defer wg.Done()
			c.addCompileCommand([]string{"cc", "-c", obj}, obj)
		}()
		go func() {
			defer wg.Done()
			c.depTracker.SetMostRecent(obj, time.Now())
		}()
		go func() {
			defer wg.Done()
			if err := c.depTracker.ProcessFileTime(obj); err != nil {
				t.Error(err)
			}
		}()
	}
	wg.Wait()

	if got := len(c.GetCompileCommands()); got != n {
		t.Errorf("expected %d compile commands, got %d", n, got)
	}
}

// The dependency file must be generated by the compile itself and used to
// decide whether a later compile is required.
func TestCompileGeneratesDepsFile(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("uses a shell script as a fake compiler")
	}

	dir := t.TempDir()
	t.Chdir(dir)

	// Fake compiler writing the object and dependency files like gcc -MMD.
	cc := filepath.Join(dir, "fake-cc")
	script := "#!/bin/sh\n" +
		"while [ $# -gt 0 ]; do\n" +
		"  case \"$1\" in\n" +
		"    -MF) dep=\"$2\"; shift;;\n" +
		"    -o) obj=\"$2\"; shift;;\n" +
		"    -*) ;;\n" +
		"    *) src=\"$1\";;\n" +
		"  esac\n" +
		"  shift\n" +
		"done\n" +
		"printf '%s: %s src/a.h\\n' \"$obj\" \"$src\" > \"$dep\"\n" +
		": > \"$obj\"\n"
	if err := os.WriteFile(cc, []byte(script), 0755); err != nil {
		t.Fatal(err)
	}

	c := newTestCompiler()
	c.ccPath = cc
	c.baseDir = dir
	c.dstDir = "bin"
	src := dir + "/src/a.c"
	hdr := dir + "/src/a.h"

	if err := os.MkdirAll(filepath.Dir(src), 0755); err != nil {
		t.Fatal(err)
	}
	for _, f := range []string{src, hdr} {
		if err := os.WriteFile(f, nil, 0644); err != nil {
			t.Fatal(err)
		}
	}
	old := time.Now().Add(-time.Hour)
	for _, f := range []string{src, hdr} {
		if err := os.Chtimes(f, old, old); err != nil {
			t.Fatal(err)
		}
	}

	required, err := c.depTracker.CompileRequired(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatal(err)
	}
	if !required {
		t.Fatalf("compile not required for new object file")
	}

	if err := c.CompileFile(src, COMPILER_TYPE_C); err != nil {
		t.Fatal(err)
	}

	deps, err := ParseDepsFile(c.dstFilePath(src) + ".d")
	if err != nil {
		t.Fatal(err)
	}
	exp := []string{"src/a.c", "src/a.h"}
	if !slices.Equal(deps, exp) {
		t.Errorf("unexpected dependencies: expected %q, got %q", exp, deps)
	}

	for _, cmd := range c.GetCompileCommands() {
		if strings.Contains(cmd.Command, "-MMD") ||
			strings.Contains(cmd.Command, "-MF") {

			t.Errorf("dependency options in compile command: %s",
				cmd.Command)
		}
	}

	required, err = c.depTracker.CompileRequired(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatal(err)
	}
	if required {
		t.Errorf("compile required for up to date object file")
	}

	now := time.Now().Add(time.Minute)
	if err := os.Chtimes(hdr, now, now); err != nil {
		t.Fatal(err)
	}

	required, err = c.depTracker.CompileRequired(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatal(err)
	}
	if !required {
		t.Errorf("compile not required after header was modified")
	}
}

// An object file without dependency file (e.g., built by an older newt) must
// be rebuilt, as it is not known which headers it depends on.
func TestCompileRequiredMissingDepsFile(t *testing.T) {
	dir := t.TempDir()
	c := newTestCompiler()
	c.ccPath = "cc"
	c.baseDir = dir
	c.dstDir = dir + "/bin"
	src := dir + "/src/a.c"
	dst := c.dstFilePath(src)

	if err := os.MkdirAll(filepath.Dir(src), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(src, nil, 0644); err != nil {
		t.Fatal(err)
	}

	cmd, err := c.CompileFileCmd(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatal(err)
	}
	if err := writeCommandFile(dst+".o", cmd); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(dst+".o", nil, 0644); err != nil {
		t.Fatal(err)
	}

	old := time.Now().Add(-time.Hour)
	if err := os.Chtimes(src, old, old); err != nil {
		t.Fatal(err)
	}

	required, err := c.depTracker.CompileRequired(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}
	if !required {
		t.Errorf("compile not required without dependency file")
	}
}

func TestStripDepsFlags(t *testing.T) {
	cmd := []string{"cc", "-Wall", "-MMD", "-MF", "bin/a.d", "-c", "-o",
		"bin/a.o", "a.c"}
	exp := []string{"cc", "-Wall", "-c", "-o", "bin/a.o", "a.c"}

	if got := stripDepsFlags(cmd); !slices.Equal(got, exp) {
		t.Errorf("expected %q, got %q", exp, got)
	}
}

func TestParseDepsFileEscaping(t *testing.T) {
	dir := t.TempDir()
	obj := dir + "/my dir/my file.o"

	// As generated by gcc -MM / -MMD for "my dir/my file.c", followed by the line
	// newt appends itself.
	content := "my\\ file.o: my\\ dir/my\\ file.c inc/a\\#b.h \\\n" +
		" inc/c$$d.h \\\n" +
		" inc/plain.h\n" +
		escapeDepsPath(obj) + ": \n"

	path := filepath.Join(dir, "my file.d")
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}

	deps, err := ParseDepsFile(path)
	if err != nil {
		t.Fatal(err)
	}

	exp := []string{"my dir/my file.c", "inc/a#b.h", "inc/c$d.h",
		"inc/plain.h"}
	if !slices.Equal(deps, exp) {
		t.Errorf("unexpected dependencies: expected %q, got %q", exp, deps)
	}
}

func TestParseDepsLine(t *testing.T) {
	tests := []struct {
		line string
		obj  string
		deps []string
		err  bool
	}{
		{"", "", nil, false},
		{"   ", "", nil, false},
		{"a.o: a.c b.h", "a.o", []string{"a.c", "b.h"}, false},
		{"a.o:", "a.o", []string{}, false},
		{"C:/x/a.o: C:/x/a.c", "C:/x/a.o", []string{"C:/x/a.c"}, false},
		{"a\\ b.o: a\\ b.c\tc.h\r", "a b.o", []string{"a b.c", "c.h"}, false},
		{"a\\\\b.o: c\\d.h", "a\\\\b.o", []string{"c\\d.h"}, false},
		{"a.c b.h", "", nil, true},
	}

	for _, tc := range tests {
		obj, deps, err := parseDepsLine(tc.line)
		if (err != nil) != tc.err {
			t.Errorf("%q: unexpected error result: %v", tc.line, err)
			continue
		}
		if obj != tc.obj || !slices.Equal(deps, tc.deps) {
			t.Errorf("%q: expected %q %q, got %q %q", tc.line, tc.obj,
				tc.deps, obj, deps)
		}
	}
}

func TestEscapeDepsPath(t *testing.T) {
	for _, p := range []string{"plain/a.o", "/sp ace/a b.o", "a#b$c.o",
		"tab\there.o"} {

		tokens := splitDepsTokens(escapeDepsPath(p) + ": x")
		if len(tokens) != 2 || tokens[0] != p+":" {
			t.Errorf("%q: escape round trip failed: %q", p, tokens)
		}
	}
}

// A dependency file which cannot be parsed (e.g., written by an older newt)
// must cause a rebuild rather than a permanent build failure.
func TestCompileRequiredCorruptDepsFile(t *testing.T) {
	// Project base path always uses forward slashes.
	dir := filepath.ToSlash(t.TempDir())
	c := newTestCompiler()
	c.ccPath = "cc"
	c.baseDir = dir
	c.dstDir = dir + "/bin"
	src := dir + "/src/a.c"
	dst := c.dstFilePath(src)

	if err := os.MkdirAll(filepath.Dir(src), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(src, nil, 0644); err != nil {
		t.Fatal(err)
	}

	cmd, err := c.CompileFileCmd(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatal(err)
	}
	if err := writeCommandFile(dst+".o", cmd); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(dst+".d", []byte("no colon here\n"),
		0644); err != nil {

		t.Fatal(err)
	}
	if err := os.WriteFile(dst+".o", nil, 0644); err != nil {
		t.Fatal(err)
	}

	// Make sure the source is older than the object and dependency files.
	old := time.Now().Add(-time.Hour)
	if err := os.Chtimes(src, old, old); err != nil {
		t.Fatal(err)
	}

	required, err := c.depTracker.CompileRequired(src, COMPILER_TYPE_C)
	if err != nil {
		t.Fatalf("unexpected error: %s", err)
	}
	if !required {
		t.Errorf("compile not required with corrupt dependency file")
	}
	if _, err := os.Stat(dst + ".d"); !os.IsNotExist(err) {
		t.Errorf("corrupt dependency file not removed")
	}
}
