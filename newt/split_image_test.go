// splitImageElfSymbols returns the symbols of an ELF file by name.
func splitImageElfSymbols(t *testing.T, path string) map[string]elf.Symbol {
	t.Helper()

	f, err := elf.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()

	syms, err := f.Symbols()
	if err != nil {
		t.Fatal(err)
	}

	m := map[string]elf.Symbol{}
	for _, s := range syms {
		m[s.Name] = s
	}

	return m
}

// TestBuildSplitImage builds a split image using the host toolchain.  The
// target uses an autogenerated linker script, a whole-archive package shared
// by the loader and the app, and a global symbol with the same name in both
// app packages.
func TestBuildSplitImage(t *testing.T) {
	// Split images are linked with GNU ld options.
	if runtime.GOOS != "linux" {
		t.Skip("split image host build supported only on Linux")
	}

	tools := map[string]string{}
	for _, name := range []string{"cc", "ar", "objdump", "objcopy", "size"} {
		path, err := exec.LookPath(name)
		if err != nil {
			t.Skipf("%s not found in PATH", name)
		}
		tools[name] = path
	}

	dir := t.TempDir()
	if err := copy.Copy(filepath.Join("testdata", "split_image"),
		dir); err != nil {

		t.Fatal(err)
	}

	buildSpaceWriteFile(t, filepath.Join(dir, "repos", "apache-mynewt-core",
		"compiler", "sim", "compiler.yml"),
		"compiler.path.cc: \""+tools["cc"]+"\"\n"+
			"compiler.path.as: \""+tools["cc"]+"\"\n"+
			"compiler.path.archive: \""+tools["ar"]+"\"\n"+
			"compiler.path.objdump: \""+tools["objdump"]+"\"\n"+
			"compiler.path.objcopy: \""+tools["objcopy"]+"\"\n"+
			"compiler.path.objsize: \""+tools["size"]+"\"\n"+
			"compiler.flags.default: [-O1, -fno-common]\n"+
			"compiler.ld.flags: [-nostdlib, -static, -no-pie, "+
			"\"-Wl,--entry=main\"]\n"+
			"compiler.ld.binfile: false\n")

	out, err := newtCombinedOutput(dir, nil, "build", "split")
	if err != nil {
		t.Fatalf("newt build failed: %s\n%s", err, out)
	}

	bin := filepath.Join(dir, "bin", "targets", "split")
	loader := splitImageElfSymbols(t,
		filepath.Join(bin, "loader", "apps", "loader", "loader.elf"))
	app := splitImageElfSymbols(t,
		filepath.Join(bin, "app", "apps", "app", "app.elf"))

	// The shared package is linked into the loader only.  The app refers to
	// the loader's copy through the ROM ELF symbols, which are absolute.
	for _, name := range []string{"shared_fn", "shared_state"} {
		if s, ok := loader[name]; !ok || s.Section == elf.SHN_ABS {
			t.Errorf("%s not defined in loader", name)
		}
		if s, ok := app[name]; !ok || s.Section != elf.SHN_ABS {
			t.Errorf("%s not taken from loader in app", name)
		}
	}

	// Each image has its own copy of the app package symbol.
	for img, syms := range map[string]map[string]elf.Symbol{
		"loader": loader, "app": app} {

		if s, ok := syms["app_state"]; !ok || s.Section == elf.SHN_ABS {
			t.Errorf("app_state not defined in %s", img)
		}
	}
}
